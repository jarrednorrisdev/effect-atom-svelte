<h1>effect-atom-svelte</h1>
<p>
  Svelte 5 bindings for Effect Atom. Each page shows one area working against a demo API that serves
  the same todo store over Effect <code>HttpApi</code> and Effect RPC.
</p>
<ul>
  <li><a href="/basics">Basics</a>: reading, writing, binding and deriving atoms.</li>
  <li><a href="/rpc">RPC</a>: <code>AtomRpc</code> queries, mutations, typed errors and families, rendered on the server.</li>
  <li><a href="/http">HTTP API</a>: the same through <code>AtomHttpApi</code>, with query and path params.</li>
  <li><a href="/suspense">Suspense</a>: <code>await</code> in markup with boundaries for pending and failed states.</li>
  <li><a href="/mutations">Mutations</a>: <code>Atom.fn</code> promise modes, interruption, reset and optimistic updates.</li>
  <li><a href="/streams">Streams</a>: stream atoms and a streaming RPC pulled chunk by chunk.</li>
  <li><a href="/refs">Refs and scopes</a>: <code>AtomRef</code> and <code>ScopedAtom</code>.</li>
  <li><a href="/browser">Browser atoms</a>: <code>kvs</code>, <code>searchParam</code>, <code>debounce</code> and refresh on focus.</li>
  <li><a href="/lifetimes">Lifetimes</a>: mounting, <code>keepAlive</code> and idle TTLs.</li>
</ul>
